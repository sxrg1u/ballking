// Balancing tool. Run with:  node tools/calibrate.js
// Simulates a player who always buys the upgrade with the best value per TP,
// then rewrites js/ratingTable.js so ratings are reached at the target times.
import { writeFileSync } from 'node:fs';
import {
  newState, tick, expectedStreak, tpPerSec, upgradeCost, buyUpgrade, buyOneOff,
  oneOffCost, isUnlocked, ratingFromXp, currentStar,
} from '../js/engine.js';
import { RATING_XP, EXT_GROWTH } from '../js/ratingTable.js';
import { UPGRADE_ORDER, GROUNDS, COACHES, GEAR } from '../js/config.js';

// Target active play time (hours) for selected ratings; linear in between.
const ANCHORS = [
  [1, 0], [2, 0.003], [5, 0.03], [10, 0.12], [15, 0.33], [25, 1], [35, 2],
  [45, 4.5], [55, 8], [65, 16], [72, 25], [80, 40], [85, 55], [90, 73],
  [94, 90], [97, 108], [98, 120], [99, 135],
];
const POST_99_FIRST_STEP_H = 12; // rating 100 about 12 h after Messi

function targetHours(r) {
  for (let i = 1; i < ANCHORS.length; i++) {
    const [r0, h0] = ANCHORS[i - 1], [r1, h1] = ANCHORS[i];
    if (r <= r1) return h0 + (h1 - h0) * (r - r0) / (r1 - r0);
  }
  return ANCHORS[ANCHORS.length - 1][1];
}

const ONEOFFS = [...GROUNDS, ...COACHES, ...GEAR];
const prod = s => tpPerSec(s, expectedStreak(s), s.highestRating);

// Buy greedily: best (relative gain / cost); wait if the best is too expensive.
function greedy(s) {
  for (let guard = 0; guard < 500; guard++) {
    const base = prod(s);
    let best = null;
    for (const id of UPGRADE_ORDER) {
      const cost = upgradeCost(id, s.levels[id]);
      s.levels[id]++;
      const gain = prod(s) / base - 1;
      s.levels[id]--;
      const score = gain / cost;
      if (gain > 0 && (!best || score > best.score)) best = { score, cost, buy: () => buyUpgrade(s, id, 1) };
    }
    for (const it of ONEOFFS) {
      if (s.owned[it.id] || !isUnlocked(s, it)) continue;
      const cost = oneOffCost(it);
      const score = (it.mult - 1) / cost;
      if (!best || score > best.score) best = { score, cost, buy: () => buyOneOff(s, it.id) };
    }
    if (!best || best.cost > s.tp) return;
    best.buy();
  }
}

// Run the simulation; calls onStep(tSeconds, state) after each step.
function simulate(hours, onStep) {
  const s = newState();
  let t = 0;
  while (t < hours * 3600) {
    const dt = t < 600 ? 1 : t < 7200 ? 3 : 15;
    greedy(s);
    tick(s, dt, expectedStreak(s));
    t += dt;
    onStep(t, s);
  }
  return s;
}

function xpAtTargets() {
  const targets = [];
  for (let r = 2; r <= 99; r++) targets.push({ r, t: targetHours(r) * 3600 });
  const res = {};
  let i = 0;
  simulate(targetHours(99) + 0.1, (t, s) => {
    while (i < targets.length && t >= targets[i].t) { res[targets[i].r] = s.xp; i++; }
  });
  return res;
}

// ---- Fixed-point iteration ----
for (let it = 0; it < 25; it++) {
  const xp = xpAtTargets();
  let maxErr = 0;
  for (let r = 2; r <= 99; r++) {
    const next = Math.max(xp[r], 1);
    const mixed = Math.exp(0.5 * Math.log(RATING_XP[r]) + 0.5 * Math.log(next));
    maxErr = Math.max(maxErr, Math.abs(Math.log(next / RATING_XP[r])));
    RATING_XP[r] = mixed;
  }
  for (let r = 3; r <= 99; r++) RATING_XP[r] = Math.max(RATING_XP[r], RATING_XP[r - 1] * 1.02);
  if (maxErr < 0.01) break;
}

// ---- Growth factor after 99 ----
let xp99At = null, xpAfter = null;
const t99 = targetHours(99) * 3600, tAfter = t99 + POST_99_FIRST_STEP_H * 3600;
simulate(targetHours(99) + POST_99_FIRST_STEP_H + 0.1, (t, s) => {
  if (xp99At === null && t >= t99) xp99At = s.xp;
  if (xpAfter === null && t >= tAfter) xpAfter = s.xp;
});
const growth = Math.max(1.05, xpAfter / RATING_XP[99]);

const table = RATING_XP.map(v => (v ? Number(v.toPrecision(5)) : 0));
writeFileSync(new URL('../js/ratingTable.js', import.meta.url),
  '// Generated by tools/calibrate.js - do not edit by hand.\n' +
  `export const RATING_XP = ${JSON.stringify(table)};\n` +
  `export const EXT_GROWTH = ${growth.toFixed(4)};\n`);

// ---- Report (uses the table in memory; EXT_GROWTH applies after a re-run) ----
console.log(`EXT_GROWTH written: ${growth.toFixed(4)} (loaded this run: ${EXT_GROWTH})`);
const reached = {};
let lastStar = null;
const starLog = [];
const end = simulate(targetHours(99) + 200, (t, s) => {
  const r = ratingFromXp(s.xp);
  if (!reached[r]) reached[r] = t;
  const st = currentStar(r);
  if (st !== lastStar) { starLog.push(`${(t / 3600).toFixed(2).padStart(7)} h  ${st.name} (${st.rating})`); lastStar = st; }
});
const fmtH = sec => (sec / 3600).toFixed(2) + ' h';
console.log('\nRating  target    simulated');
for (const r of [2, 5, 10, 15, 25, 35, 45, 55, 65, 72, 80, 85, 90, 94, 97, 99, 100, 101, 102, 103, 105, 108, 110, 115]) {
  const tgt = r <= 99 ? targetHours(r).toFixed(2) + ' h' : '-';
  console.log(String(r).padStart(6), tgt.padStart(9), reached[r] ? fmtH(reached[r]).padStart(11) : '  not yet');
}
console.log('\nPlayer switches:\n' + starLog.join('\n'));
console.log('\nLevels at end:', end.levels, 'owned:', Object.keys(end.owned).length);
